"""Curation source for ``data/skills.json``.

The skill graph is hand-authored, not generated by a model. Keeping the authored
form here -- as compact tuples rather than 150 blocks of JSON -- means an edge
can be reviewed, argued with and changed in one line, and the emitted JSON stays
a build artifact rather than something edited by hand and drifted out of shape.

Every tuple is ``(id, name, difficulty, est_hours, prerequisites, description,
keywords, assessable)``.

The rule applied to every edge: it is present only if the dependent skill is
genuinely *unlearnable* first. "You cannot derive gradient descent without
derivatives" is an edge. "Both are machine learning" is a track label. Where the
call was arguable it is noted in DECISIONS.md.

Run ``python -m scripts.build_skills`` from ``backend/`` to regenerate.
"""

