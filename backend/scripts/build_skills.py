def to_json() -> list[dict[str, Any]]:
    """Flatten the authored tuples into the on-disk record shape."""
    records: list[dict[str, Any]] = []
    for track, nodes in TRACKS.items():
        for node_id, name, difficulty, hours, prereqs, description, keywords, assessable in nodes:
            records.append(
                {
                    "id": node_id,
                    "name": name,
                    "track": track,
                    "description": description,
                    "prerequisites": prereqs,
                    "difficulty": difficulty,
                    "est_hours": hours,
                    "assessable": assessable,
                    "keywords": keywords,
                }
            )
    return records


def main() -> int:
    """Emit skills.json, then load it back through the validator as a check."""
    configure_logging("INFO")
    records = to_json()
    graph = build_graph(records)  # raises on cycles, duplicates or dangling ids

    target = get_settings().data_dir / "skills.json"
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(json.dumps(records, indent=1, ensure_ascii=False) + "\n", encoding="utf-8")

    logger.info("wrote %s: %d nodes, %d tracks", target, len(graph), len(graph.tracks))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
